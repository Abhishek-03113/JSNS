/**
 * Writes src/generated/assets.ts: the pages, stylesheet, browser scripts (bundled per page) and SQL
 * migrations as plain string constants. Bundlers such as Vercel's then carry them with no
 * file reads or text-import support needed at runtime.
 *
 *   bun run embed          write the file
 *   bun run embed --check  exit 1 if the file is out of date (used by the tests)
 */
import { readdirSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const web = join(root, "src", "web");
const OUT = join(root, "src", "generated", "assets.ts");

/** Pages served as-is and the browser scripts bundled for them (one bundle per page). */
const PAGES = ["login.html", "builder.html", "forms.html", "connectors.html"];
const SCRIPTS = ["builder.ts", "forms.ts", "connectors.ts"];

async function bundle(entry: string): Promise<string> {
  const out = await Bun.build({ entrypoints: [join(web, entry)], target: "browser", minify: true });
  if (!out.success) throw new Error(`Bundling ${entry} failed:\n` + out.logs.join("\n"));
  return out.outputs[0]!.text();
}

export async function renderAssets(): Promise<string> {
  const read = (p: string) => Bun.file(p).text();
  const hash = (body: string) => new Bun.CryptoHasher("sha256").update(body).digest("hex").slice(0, 12);
  const asset = (body: string, type: string) => ({ body, type, hash: hash(body) });
  const assets: Record<string, { body: string; type: string; hash: string }> = {
    "styles.css": asset(await read(join(web, "styles.css")), "text/css; charset=utf-8"),
    "favicon.svg": asset(await read(join(web, "favicon.svg")), "image/svg+xml"),
  };
  for (const script of SCRIPTS) assets[script.replace(/\.ts$/, ".js")] = asset(await bundle(script), "text/javascript; charset=utf-8");
  // Pages point at /assets/<name>?v=<hash>, so assets can be cached forever and still update.
  const versioned = (html: string) =>
    html.replace(/\/assets\/([a-z0-9.-]+)(?=["'])/g, (m, name: string) => (assets[name] ? `/assets/${name}?v=${assets[name]!.hash}` : m));
  for (const page of PAGES) assets[page] = asset(versioned(await read(join(web, page))), "text/html; charset=utf-8");
  const migrationsDir = join(root, "migrations");
  const migrations = [];
  for (const name of readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort()) {
    migrations.push({ name, sql: await read(join(migrationsDir, name)) });
  }
  return [
    "// Generated by scripts/embed-assets.ts from src/web/ and migrations/. Do not edit; run `bun run embed`.",
    "",
    "export const ASSETS: Record<string, { body: string; type: string; hash: string }> = " + JSON.stringify(assets, null, 2) + ";",
    "",
    "export const MIGRATIONS: { name: string; sql: string }[] = " + JSON.stringify(migrations, null, 2) + ";",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const next = await renderAssets();
  const current = await Bun.file(OUT).text().catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("src/generated/assets.ts is out of date. Run `bun run embed`.");
      process.exit(1);
    }
  } else if (current !== next) {
    await Bun.write(OUT, next);
    console.log("Wrote src/generated/assets.ts");
  }
}
